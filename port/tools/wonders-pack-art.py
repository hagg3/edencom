def tile(src, name):
    """A Kenney tile as 32x32 RGBA."""
    im = Image.open(os.path.join(src, name)).convert("RGBA")
    if im.size != (48, 48):
        im = im.resize((48, 48), Image.NEAREST)
    return im.resize((32, 32), Image.BOX)


def stamp(base, icon):
    """Draws ICONS[icon] at 2x; an optional third entry is a drop-shadow colour (one icon pixel down-right)."""
    rows, pal = ICONS[icon][:2]
    shadow = ICONS[icon][2] if len(ICONS[icon]) > 2 else None
    rows = rows.strip("\n").split("\n")
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), icon
    px = base.load()
    passes = ([(1, lambda ch: shadow)] if shadow else []) + [(0, lambda ch: pal[ch])]
    for off, colour in passes:
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if ch == "." or x + off > 15 or y + off > 15:
                    continue
                c = colour(ch) + (255,)
                for dy in (0, 1):
                    for dx in (0, 1):
                        px[2 * (x + off) + dx, 2 * (y + off) + dy] = c
    return base


def recolour(im, f):
    """f(r, g, b) -> (r, g, b) on every pixel, alpha kept."""
    out = im.copy()
    px = out.load()
    for y in range(out.size[1]):
        for x in range(out.size[0]):
            r, g, b, a = px[x, y]
            px[x, y] = tuple(max(0, min(255, int(v))) for v in f(r, g, b)) + (a,)
    return out


def grey(im, lo, hi):
    """Greyscale stretched to lo..hi: art for a block that paint or "color" tints."""
    def f(r, g, b):
        v = (0.3 * r + 0.59 * g + 0.11 * b) / 255.0
        return (lo + (hi - lo) * v,) * 3
    return recolour(im, f)


def crate(src):
    """Pine planks with a dark frame: the look of the kits."""
    im = tile(src, "default_pine_wood.png")
    px = im.load()
    for i in range(32):
        for j in (0, 1, 30, 31):
            px[i, j] = px[j, i] = (70, 45, 25, 255)
        for j in (2, 29):
            px[i, j] = px[j, i] = (110, 75, 40, 255) if 1 < i < 30 else px[i, j]
    return im


def noise_fill(rgb, spread, seed):
    rnd = random.Random(seed)
    im = Image.new("RGBA", (32, 32))
    px = im.load()
    for y in range(32):
        for x in range(32):
            d = rnd.randint(-spread, spread)
            px[x, y] = tuple(max(0, min(255, c + d)) for c in rgb) + (255,)
    return im


def border(im, rgb, width=1):
    px = im.load()
    for i in range(32):
        for j in range(width):
            for (a, b) in ((i, j), (i, 31 - j), (j, i), (31 - j, i)):
                px[a, b] = rgb + (255,)
    return im


def paint_brick(src):
    # paint multiplies the grey, so the bricks must be near white and the mortar darker. The bricks are the
    # saturated pixels (orange) and the mortar the grey ones, so the grey comes from the saturation.
    im = tile(src, "default_brick.png")
    _, sat, val = im.convert("RGB").convert("HSV").split()
    g = Image.new("L", im.size)
    g.putdata([min(255, int(130 + 0.35 * s + 0.15 * v)) for s, v in zip(sat.tobytes(), val.tobytes())])
    return Image.merge("RGBA", (g, g, g, im.getchannel("A")))


def build(src):
    """name -> (image, transparent)"""
    t = {}
    # Building blocks (Kenney art as is, or greyed so "color"/paint tints it).
    t["pine_log"] = (tile(src, "default_pine_tree.png"), False)
    t["pine_log_top"] = (tile(src, "default_pine_tree_top.png"), False)
    t["pine_planks"] = (tile(src, "default_pine_wood.png"), False)
    t["pine_needles"] = (tile(src, "default_pine_needles.png"), True)
    t["paint_brick"] = (paint_brick(src), False)
    t["paint_brick_color"] = (tile(src, "default_brick.png"), False)
    t["sandstone_bricks"] = (tile(src, "default_sandstone_brick.png"), False)
    t["stone_bricks"] = (tile(src, "default_stone_brick.png"), False)
    t["obsidian_bricks"] = (tile(src, "default_obsidian_brick.png"), False)
    t["ice"] = (tile(src, "default_ice.png"), False)
    t["bounce"] = (grey(tile(src, "default_clay.png"), 170, 255), False)
    t["framed_glass"] = (tile(src, "default_glass.png"), True)
    # The wonder blocks: a Kenney base with an icon.
    t["crate"] = (crate(src), False)
    t["house_kit"] = (stamp(crate(src), "house"), False)
    t["bridge_kit"] = (stamp(crate(src), "bridge"), False)
    pad = grey(tile(src, "default_stone_block.png"), 150, 215)
    t["warp_side"] = (pad, False)
    t["warp_top"] = (stamp(pad.copy(), "swirl"), False)
    t["lucky"] = (stamp(border(noise_fill((250, 205, 40), 10, 7), (215, 140, 20), 2), "lucky"), False)
    t["sun_stone"] = (stamp(tile(src, "default_stone.png"), "sun"), False)
    t["moon_stone"] = (stamp(tile(src, "default_obsidian_block.png"), "moon"), False)
    t["rain_stone"] = (stamp(tile(src, "default_stone_block.png"), "cloud"), False)
    gold = tile(src, "default_stone.png")
    gold.alpha_composite(tile(src, "default_mineral_gold.png"))
    t["gold_ore"] = (gold, False)
    t["first_aid"] = (stamp(border(noise_fill((245, 245, 240), 6, 3), (200, 200, 200), 2), "cross"), False)
    t["guide"] = (stamp(tile(src, "default_stone_block.png"), "info"), False)
    t["sapling"] = (stamp(Image.new("RGBA", (32, 32), (0, 0, 0, 0)), "sapling"), True)
    t["egg"] = (stamp(Image.new("RGBA", (32, 32), (0, 0, 0, 0)), "egg"), True)
    return t


def main(src, out):
    os.makedirs(out, exist_ok=True)
    tiles = build(src)
    for name, (im, transparent) in tiles.items():
        if not transparent:
            flat = Image.new("RGBA", im.size, (0, 0, 0, 255))
            flat.alpha_composite(im)
            im = flat.convert("RGB")
        im.save(os.path.join(out, name + ".png"), optimize=True)
    print("wrote %d tiles to %s" % (len(tiles), out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
